-- CamerLink Growth Suite: demandes de devis.
-- À appliquer d'abord sur une base de test, puis après revue sur production.
create table if not exists public.quote_requests (
  id bigint generated by default as identity primary key,
  requester_id uuid not null references auth.users(id) on delete cascade,
  artisan_id uuid references auth.users(id) on delete set null,
  service text not null check (char_length(trim(service)) between 2 and 100),
  city text not null check (char_length(trim(city)) between 2 and 80),
  budget_fcfa bigint check (budget_fcfa is null or budget_fcfa between 0 and 1000000000),
  details text not null check (char_length(trim(details)) between 10 and 2000),
  status text not null default 'pending' check (status in ('pending','quoted','accepted','rejected','cancelled','completed')),
  quote_fcfa bigint check (quote_fcfa is null or quote_fcfa between 0 and 1000000000),
  artisan_response text check (artisan_response is null or char_length(artisan_response) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists quote_requests_requester_created_idx
  on public.quote_requests (requester_id, created_at desc);
create index if not exists quote_requests_artisan_created_idx
  on public.quote_requests (artisan_id, created_at desc);

alter table public.quote_requests enable row level security;

drop policy if exists "quote_requests_insert_own" on public.quote_requests;
create policy "quote_requests_insert_own" on public.quote_requests
  for insert to authenticated
  with check (
    requester_id = (select auth.uid())
    and status = 'pending'
    and quote_fcfa is null
    and artisan_response is null
  );

drop policy if exists "quote_requests_read_participant" on public.quote_requests;
create policy "quote_requests_read_participant" on public.quote_requests
  for select to authenticated
  using (requester_id = (select auth.uid()) or artisan_id = (select auth.uid()));

-- An artisan may answer only a request currently pending and assigned to them.
-- The column-level UPDATE grant below prevents changing requester_id/artisan_id/details.
drop policy if exists "quote_requests_update_assigned_artisan" on public.quote_requests;
create policy "quote_requests_update_assigned_artisan" on public.quote_requests
  for update to authenticated
  using (artisan_id = (select auth.uid()) and status = 'pending')
  with check (
    artisan_id = (select auth.uid())
    and status in ('quoted','rejected')
  );

-- A requester may cancel only their own pending request and cannot set a quote.
drop policy if exists "quote_requests_cancel_own" on public.quote_requests;
create policy "quote_requests_cancel_own" on public.quote_requests
  for update to authenticated
  using (requester_id = (select auth.uid()) and status = 'pending')
  with check (
    requester_id = (select auth.uid())
    and status = 'cancelled'
    and quote_fcfa is null
    and artisan_response is null
  );

revoke all on public.quote_requests from anon;
grant select, insert on public.quote_requests to authenticated;
grant update (status, quote_fcfa, artisan_response, updated_at) on public.quote_requests to authenticated;
grant usage, select on sequence public.quote_requests_id_seq to authenticated;
