-- 5. DEMANDES PREMIUM (boost d'annonce / premium boutique) -------------------
create table if not exists public.premium_requests (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  type text not null check (type in ('boost','premium_boutique')),
  annonce_id bigint references public.annonces(id) on delete cascade,
  etablissement_id bigint references public.etablissements(id) on delete cascade,
  message text check (char_length(message) <= 500),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  processed_at timestamptz,
  constraint premium_requests_target_check check (annonce_id is not null or etablissement_id is not null)
);

create unique index if not exists premium_requests_one_pending_uidx
  on public.premium_requests (user_id, type, coalesce(annonce_id, 0), coalesce(etablissement_id, 0))
  where status = 'pending';
create index if not exists premium_requests_user_idx on public.premium_requests (user_id);
create index if not exists premium_requests_annonce_idx
  on public.premium_requests (annonce_id) where annonce_id is not null;
create index if not exists premium_requests_etab_idx
  on public.premium_requests (etablissement_id) where etablissement_id is not null;

alter table public.premium_requests enable row level security;

drop policy if exists premium_requests_select_own on public.premium_requests;
create policy premium_requests_select_own on public.premium_requests
  for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists premium_requests_insert_own on public.premium_requests;
create policy premium_requests_insert_own on public.premium_requests
  for insert to authenticated
  with check (
    user_id = (select auth.uid())
    and status = 'pending'
    and processed_at is null
    and (premium_requests.annonce_id is null or exists (
      select 1 from public.annonces a
       where a.id = premium_requests.annonce_id and a.user_id = (select auth.uid())))
    and (premium_requests.etablissement_id is null or exists (
      select 1 from public.etablissements e
       where e.id = premium_requests.etablissement_id and e.user_id = (select auth.uid())))
  );

revoke all on public.premium_requests from anon, authenticated;
grant select on public.premium_requests to authenticated;
grant insert (user_id, type, annonce_id, etablissement_id, message) on public.premium_requests to authenticated;

create or replace function public.admin_list_premium_requests()
returns table (id bigint, user_id uuid, type text, annonce_id bigint, etablissement_id bigint,
               message text, status text, created_at timestamptz, processed_at timestamptz)
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if not public.is_admin() then
    raise exception 'accès refusé';
  end if;
  return query
    select r.id, r.user_id, r.type, r.annonce_id, r.etablissement_id,
           r.message, r.status, r.created_at, r.processed_at
      from public.premium_requests r
     order by (r.status = 'pending') desc, r.created_at desc;
end;
$function$;

create or replace function public.admin_decide_premium(p_request_id bigint, p_approve boolean, p_days integer default 30)
returns void
language plpgsql
security definer
set search_path to ''
as $function$
declare
  r public.premium_requests%rowtype;
begin
  if not public.is_admin() then
    raise exception 'accès refusé';
  end if;

  select * into r from public.premium_requests
   where id = p_request_id and status = 'pending' for update;
  if not found then
    raise exception 'demande introuvable ou déjà traitée';
  end if;

  if p_approve then
    if p_days is null or p_days < 1 or p_days > 365 then
      raise exception 'durée invalide (1 à 365 jours)';
    end if;
    insert into public.promotions (user_id, annonce_id, etablissement_id, type, status, starts_at, ends_at)
    values (r.user_id, r.annonce_id, r.etablissement_id, r.type, 'active', now(), now() + make_interval(days => p_days));
  end if;

  update public.premium_requests
     set status = case when p_approve then 'approved' else 'rejected' end,
         processed_at = now()
   where id = r.id;

  insert into public.camerlink_notifications (user_id, type, title, body)
  values (
    r.user_id, 'premium',
    case when p_approve then 'Demande Premium acceptée' else 'Demande Premium refusée' end,
    case when p_approve then format('Votre promotion est active pendant %s jours.', p_days)
         else 'Votre demande n''a pas pu être acceptée pour le moment.' end
  );
end;
$function$;

revoke execute on function public.admin_list_premium_requests() from public, anon;
revoke execute on function public.admin_decide_premium(bigint, boolean, integer) from public, anon;
grant execute on function public.admin_list_premium_requests() to authenticated;
grant execute on function public.admin_decide_premium(bigint, boolean, integer) to authenticated;


-- 6. NOTIFICATIONS AUTOMATIQUES ----------------------------------------------
create or replace function public.camerlink_notify_new_message()
returns trigger language plpgsql security definer set search_path to ''
as $function$
begin
  if new.receiver_id is not null and new.receiver_id <> new.sender_id then
    insert into public.camerlink_notifications (user_id, actor_id, type, title, body, link)
    values (new.receiver_id, new.sender_id, 'message', 'Nouveau message CamerLink',
            left(coalesce(new.content, 'Vous avez reçu un nouveau message.'), 160), '/');
  end if;
  return new;
end;
$function$;

create or replace function public.camerlink_notify_review()
returns trigger language plpgsql security definer set search_path to ''
as $function$
begin
  insert into public.camerlink_notifications (user_id, actor_id, type, title, body, link)
  values (new.artisan_id, new.reviewer_id, 'review', 'Nouvel avis en attente de validation',
          'Un client a déposé un avis sur votre profil. Il sera visible après validation.',
          '/artisan/' || new.artisan_id::text);
  return new;
end;
$function$;

create or replace function public.camerlink_notify_reel_comment()
returns trigger language plpgsql security definer set search_path to ''
as $function$
declare v_owner uuid;
begin
  select a.user_id into v_owner from public.annonces a where a.id = new.reel_id;
  if v_owner is not null and v_owner <> new.user_id then
    insert into public.camerlink_notifications (user_id, actor_id, type, title, body)
    values (v_owner, new.user_id, 'reel_comment', 'Nouveau commentaire sur votre Reel',
            'Il sera visible après validation.');
  end if;
  return new;
end;
$function$;

create or replace function public.camerlink_notify_plan_request()
returns trigger language plpgsql security definer set search_path to ''
as $function$
begin
  insert into public.camerlink_notifications (user_id, actor_id, type, title, body)
  select ad.user_id, new.user_id, 'plan_request', 'Nouvelle demande d''abonnement',
         format('Plan demandé : %s', new.plan)
    from public.admins ad;
  return new;
end;
$function$;

create or replace function public.camerlink_notify_plan_decision()
returns trigger language plpgsql security definer set search_path to ''
as $function$
begin
  if new.status is distinct from old.status then
    insert into public.camerlink_notifications (user_id, type, title, body)
    values (new.user_id, 'plan_request', 'Mise à jour de votre demande',
            format('Plan %s : %s', new.plan,
                   case new.status when 'contacted' then 'nous vous contactons'
                                   when 'approved' then 'acceptée'
                                   when 'rejected' then 'refusée'
                                   else 'en attente' end));
  end if;
  return new;
end;
$function$;

create or replace function public.notify_new_avis()
returns trigger language plpgsql security definer set search_path to ''
as $function$
declare v_owner uuid; v_title text;
begin
  select a.user_id, a.title into v_owner, v_title from public.annonces a where a.id = new.annonce_id;
  if v_owner is not null and v_owner <> new.user_id then
    insert into public.camerlink_notifications (user_id, actor_id, type, title, body)
    values (v_owner, new.user_id, 'avis', 'Nouvel avis reçu',
            format('%s/5 sur « %s »', new.note, left(coalesce(v_title, ''), 60)));
  end if;
  return new;
end;
$function$;

create or replace function public.notify_new_reel_like()
returns trigger language plpgsql security definer set search_path to ''
as $function$
declare v_owner uuid; v_title text;
begin
  select a.user_id, a.title into v_owner, v_title from public.annonces a where a.id = new.annonce_id;
  if v_owner is not null and v_owner <> new.user_id then
    insert into public.camerlink_notifications (user_id, actor_id, type, title, body)
    values (v_owner, new.user_id, 'like', 'Nouveau J''aime',
            format('« %s » a reçu un J''aime.', left(coalesce(v_title, ''), 60)));
  end if;
  return new;
end;
$function$;

