begin;

-- 1. NOTIFICATIONS ----------------------------------------------------------
create table if not exists public.camerlink_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  type text not null check (type in (
    'message','review','reel_comment','plan_request','system','avis','like','premium'
  )),
  title text not null check (char_length(title) <= 160),
  body text check (body is null or char_length(body) <= 500),
  link text check (link is null or (char_length(link) <= 300 and link ~ '^/([^/\\]|$)')),
  read_at timestamptz,
  created_at timestamptz not null default now()
);

-- Mise à niveau d'une ancienne table de notifications déjà existante :
-- élargit la contrainte de type sans dépendre du nom historique du CHECK.
do $migration$
declare c record;
begin
  for c in
    select conname
      from pg_constraint
     where conrelid = 'public.camerlink_notifications'::regclass
       and contype = 'c'
       and pg_get_constraintdef(oid) ilike '%type%'
  loop
    execute format('alter table public.camerlink_notifications drop constraint %I', c.conname);
  end loop;
end
$migration$;

alter table public.camerlink_notifications
  add constraint camerlink_notifications_type_check
  check (type in ('message','review','reel_comment','plan_request','system','avis','like','premium'));

create index if not exists camerlink_notifications_user_idx
  on public.camerlink_notifications (user_id, created_at desc);
create index if not exists camerlink_notifications_actor_idx
  on public.camerlink_notifications (actor_id) where actor_id is not null;

alter table public.camerlink_notifications enable row level security;

drop policy if exists "Users read own notifications" on public.camerlink_notifications;
create policy "Users read own notifications" on public.camerlink_notifications
  for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "Users mark own notifications read" on public.camerlink_notifications;
create policy "Users mark own notifications read" on public.camerlink_notifications
  for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- le client lit et marque comme lue (read_at uniquement) ; la création passe par des triggers serveur
revoke all on public.camerlink_notifications from anon, authenticated;
grant select on public.camerlink_notifications to authenticated;
grant update (read_at) on public.camerlink_notifications to authenticated;


-- 2. AVIS SUR LES ARTISANS (modérés par l'admin) -----------------------------
create table if not exists public.artisan_reviews (
  id bigint generated by default as identity primary key,
  artisan_id uuid not null references auth.users(id) on delete cascade,
  reviewer_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  comment text check (comment is null or char_length(comment) <= 1000),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  constraint artisan_reviews_one_per_user unique (artisan_id, reviewer_id),
  constraint artisan_reviews_not_self check (artisan_id <> reviewer_id)
);

create index if not exists artisan_reviews_public_idx
  on public.artisan_reviews (artisan_id, status, created_at desc);
create index if not exists artisan_reviews_reviewer_idx
  on public.artisan_reviews (reviewer_id);

alter table public.artisan_reviews enable row level security;

-- NB : anon ne peut pas appeler is_admin() -> la lecture admin a sa propre politique
drop policy if exists "Public reads approved artisan reviews" on public.artisan_reviews;
create policy "Public reads approved artisan reviews" on public.artisan_reviews
  for select to anon, authenticated
  using (status = 'approved' or reviewer_id = (select auth.uid()));

drop policy if exists "Admin reads all artisan reviews" on public.artisan_reviews;
create policy "Admin reads all artisan reviews" on public.artisan_reviews
  for select to authenticated using ((select public.is_admin()));

drop policy if exists "Authenticated users submit own review" on public.artisan_reviews;
create policy "Authenticated users submit own review" on public.artisan_reviews
  for insert to authenticated
  with check (reviewer_id = (select auth.uid())
              and artisan_id <> (select auth.uid())
              and status = 'pending');

drop policy if exists "Reviewer can update own pending review" on public.artisan_reviews;
create policy "Reviewer can update own pending review" on public.artisan_reviews
  for update to authenticated
  using (reviewer_id = (select auth.uid()) and status = 'pending')
  with check (reviewer_id = (select auth.uid()) and status = 'pending');

drop policy if exists "Admin moderates artisan reviews" on public.artisan_reviews;
create policy "Admin moderates artisan reviews" on public.artisan_reviews
  for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Reviewer can delete own review" on public.artisan_reviews;
create policy "Reviewer can delete own review" on public.artisan_reviews
  for delete to authenticated
  using (reviewer_id = (select auth.uid()) or (select public.is_admin()));

revoke all on public.artisan_reviews from anon, authenticated;
grant select on public.artisan_reviews to anon, authenticated;
grant insert (artisan_id, reviewer_id, rating, comment) on public.artisan_reviews to authenticated;
grant update (rating, comment, status) on public.artisan_reviews to authenticated;
grant delete on public.artisan_reviews to authenticated;


