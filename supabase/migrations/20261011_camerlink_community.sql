begin;
create table if not exists public.artisan_reviews (
 id bigint generated by default as identity primary key,
 artisan_id uuid not null references auth.users(id) on delete cascade,
 reviewer_id uuid not null references auth.users(id) on delete cascade,
 rating smallint not null check(rating between 1 and 5),
 comment text check(comment is null or char_length(comment)<=1000),
 status text not null default 'pending' check(status in('pending','approved','rejected')),
 created_at timestamptz not null default now(),
 constraint artisan_reviews_one_per_user unique(artisan_id,reviewer_id),
 constraint artisan_reviews_not_self check(artisan_id<>reviewer_id)
);
create index if not exists artisan_reviews_public_idx on public.artisan_reviews(artisan_id,status,created_at desc);
alter table public.artisan_reviews enable row level security;
drop policy if exists "Public reads approved artisan reviews" on public.artisan_reviews;
create policy "Public reads approved artisan reviews" on public.artisan_reviews for select using(status='approved' or reviewer_id=auth.uid());
drop policy if exists "Authenticated users submit own review" on public.artisan_reviews;
create policy "Authenticated users submit own review" on public.artisan_reviews for insert to authenticated with check(reviewer_id=auth.uid() and artisan_id<>auth.uid() and status='pending');
drop policy if exists "Reviewer can update own pending review" on public.artisan_reviews;
create policy "Reviewer can update own pending review" on public.artisan_reviews for update to authenticated using(reviewer_id=auth.uid() and status='pending') with check(reviewer_id=auth.uid() and status='pending');

-- Likes: public.reel_likes and reel_likes_count are already managed in Supabase.
-- Do not create, alter, or redefine them in this community migration.

create table if not exists public.reel_comments (
 id bigint generated by default as identity primary key,
 reel_id bigint not null references public.annonces(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 content text not null check(char_length(trim(content)) between 1 and 500),
 status text not null default 'pending' check(status in('pending','approved','rejected')),
 created_at timestamptz not null default now()
);
create index if not exists reel_comments_public_idx on public.reel_comments(reel_id,status,created_at desc);
alter table public.reel_comments enable row level security;
drop policy if exists "Public reads approved reel comments" on public.reel_comments;
create policy "Public reads approved reel comments" on public.reel_comments for select using(status='approved' or user_id=auth.uid());
drop policy if exists "Authenticated users submit own reel comments" on public.reel_comments;
create policy "Authenticated users submit own reel comments" on public.reel_comments for insert to authenticated with check(user_id=auth.uid() and status='pending');
drop policy if exists "Users delete own pending reel comments" on public.reel_comments;
create policy "Users delete own pending reel comments" on public.reel_comments for delete to authenticated using(user_id=auth.uid() and status='pending');

create table if not exists public.camerlink_notifications (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 actor_id uuid references auth.users(id) on delete set null,
 type text not null check(type in('message','review','reel_comment','plan_request','system')),
 title text not null check(char_length(title)<=160),
 body text check(body is null or char_length(body)<=500),
 link text,
 read_at timestamptz,
 created_at timestamptz not null default now()
);
create index if not exists camerlink_notifications_user_idx on public.camerlink_notifications(user_id,created_at desc);
alter table public.camerlink_notifications enable row level security;
drop policy if exists "Users read own notifications" on public.camerlink_notifications;
create policy "Users read own notifications" on public.camerlink_notifications for select to authenticated using(user_id=auth.uid());
drop policy if exists "Users mark own notifications read" on public.camerlink_notifications;
create policy "Users mark own notifications read" on public.camerlink_notifications for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
revoke insert,delete on public.camerlink_notifications from anon,authenticated;

create table if not exists public.artisan_plan_requests (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 plan text not null check(plan in('pro','verified')),
 status text not null default 'pending' check(status in('pending','contacted','approved','rejected')),
 created_at timestamptz not null default now(),
 constraint artisan_plan_requests_unique_pending unique(user_id,plan,status)
);
alter table public.artisan_plan_requests enable row level security;
drop policy if exists "Users view own plan requests" on public.artisan_plan_requests;
create policy "Users view own plan requests" on public.artisan_plan_requests for select to authenticated using(user_id=auth.uid());
drop policy if exists "Users create own plan requests" on public.artisan_plan_requests;
create policy "Users create own plan requests" on public.artisan_plan_requests for insert to authenticated with check(user_id=auth.uid() and status='pending');

create or replace function public.camerlink_notify_new_message()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 if new.receiver_id is not null and new.receiver_id<>new.sender_id then
  insert into public.camerlink_notifications(user_id,actor_id,type,title,body,link)
  values(new.receiver_id,new.sender_id,'message','Nouveau message CamerLink',left(coalesce(new.content,'Vous avez reçu un nouveau message.'),160),'/');
 end if;
 return new;
end; $$;
drop trigger if exists camerlink_message_notification on public.messages;
create trigger camerlink_message_notification after insert on public.messages for each row execute function public.camerlink_notify_new_message();

create or replace function public.camerlink_notify_review()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.camerlink_notifications(user_id,actor_id,type,title,body,link)
 values(new.artisan_id,new.reviewer_id,'review','Nouvel avis à valider','Un client a déposé un avis sur votre profil.','/artisan/'||new.artisan_id::text);
 return new;
end; $$;
drop trigger if exists camerlink_review_notification on public.artisan_reviews;
create trigger camerlink_review_notification after insert on public.artisan_reviews for each row execute function public.camerlink_notify_review();

grant select on public.artisan_reviews,public.reel_comments,public.camerlink_notifications,public.artisan_plan_requests to anon,authenticated;
grant insert,update on public.artisan_reviews to authenticated;
grant insert,select,delete on public.reel_comments to authenticated;
grant select,update on public.camerlink_notifications to authenticated;
grant insert,select on public.artisan_plan_requests to authenticated;
commit;
