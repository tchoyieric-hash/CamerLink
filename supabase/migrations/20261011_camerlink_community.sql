-- ----------------------------------------------------------------------------
-- Cette migration est IDEMPOTENTE : elle peut être rejouée sans erreur.
--
-- Prérequis déjà présents en base (NE PAS recréer ici) :
--   * public.reel_likes (id, annonce_id, user_id, created_at) + RLS privée
--     -> migration 20261010162545_create_reel_likes
--   * public.reel_likes_count(bigint[]) -> (annonce_id, nb), SECURITY DEFINER
--     (ne jamais la redéfinir en SECURITY INVOKER : les J'aime sont privés
--      par le RLS, le total public passerait à 0 pour les visiteurs)
--   * public.avis, public.promotions, public.messages, public.admins,
